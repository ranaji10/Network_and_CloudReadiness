"""Render docs/planning/TRACKER.md from docs/planning/tracker/*.yaml (one file per epic).

Usage:
    uv run python scripts/render_tracker.py          # rewrite TRACKER.md
    uv run python scripts/render_tracker.py --check  # exit 1 if TRACKER.md is stale
"""

from __future__ import annotations

import sys
from collections import Counter
from pathlib import Path
from typing import Literal

import yaml
from pydantic import BaseModel, ValidationError, field_validator

ROOT = Path(__file__).resolve().parents[1]
TRACKER_DIR = ROOT / "docs" / "planning" / "tracker"
OUT = ROOT / "docs" / "planning" / "TRACKER.md"
STATUSES = ("todo", "in_progress", "blocked", "done")
PHASE_NAMES = {
    0: "Foundation",
    1: "MVP for one analyst",
    2: "Cloud ingestion and multi-tenant",
    3: "Recommendations depth and AWS",
    4: "Agentic-AI depth and product polish",
    5: "Hardening and commercial",
}


class Story(BaseModel):
    id: str
    title: str
    status: Literal["todo", "in_progress", "blocked", "done"]
    phase: int
    owner: str = ""
    branch: str = ""
    depends_on: list[str] = []
    acceptance: str = ""
    notes: str = ""

    @field_validator("phase")
    @classmethod
    def _phase_range(cls, v: int) -> int:
        if v not in PHASE_NAMES:
            raise ValueError(f"phase must be one of {sorted(PHASE_NAMES)}")
        return v


class Epic(BaseModel):
    epic: str
    name: str
    owner_hint: str = ""
    stories: list[Story]


def load_epics() -> list[Epic]:
    epics: list[Epic] = []
    errors: list[str] = []
    for path in sorted(TRACKER_DIR.glob("*.yaml")):
        try:
            epic = Epic.model_validate(yaml.safe_load(path.read_text()))
        except ValidationError as exc:
            errors.append(f"{path.name}: {exc}")
            continue
        if path.stem != epic.epic:
            errors.append(f"{path.name}: file name must match epic id '{epic.epic}'")
        for s in epic.stories:
            if not s.id.startswith(epic.epic + "-"):
                errors.append(f"{path.name}: story {s.id} must be prefixed '{epic.epic}-'")
        epics.append(epic)
    ids = [s.id for e in epics for s in e.stories]
    dupes = sorted({i for i in ids if ids.count(i) > 1})
    if dupes:
        errors.append(f"duplicate story ids: {dupes}")
    known = set(ids)
    for e in epics:
        for s in e.stories:
            for d in s.depends_on:
                if d not in known:
                    errors.append(f"{s.id} depends on unknown story {d}")
            if s.status == "in_progress" and not s.owner:
                errors.append(f"{s.id} is in_progress but has no owner")
    if errors:
        print("tracker validation failed:", file=sys.stderr)
        for e in errors:
            print(f"  - {e}", file=sys.stderr)
        sys.exit(2)
    return epics


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render(epics: list[Epic]) -> str:
    lines: list[str] = []
    lines.append("# Tracker")
    lines.append("")
    lines.append(
        "<!-- GENERATED by scripts/render_tracker.py from docs/planning/tracker/*.yaml. "
        "Do not edit by hand; edit the YAML and run `make tracker`. -->"
    )
    lines.append("")
    lines.append(
        "Source of truth: `docs/planning/tracker/<EPIC>.yaml`. Phases are described in `docs/product/ROADMAP.md`."
    )
    lines.append("")
    all_stories = [(e, s) for e in epics for s in e.stories]
    total = Counter(s.status for _, s in all_stories)
    lines.append("## Summary")
    lines.append("")
    lines.append("| Epic | Name | todo | in_progress | blocked | done | total |")
    lines.append("|---|---|---:|---:|---:|---:|---:|")
    for e in epics:
        c = Counter(s.status for s in e.stories)
        lines.append(
            f"| {e.epic} | {_cell(e.name)} | {c['todo']} | {c['in_progress']} | {c['blocked']} | {c['done']} | "
            f"{len(e.stories)} |"
        )
    lines.append(
        f"| **All** | | {total['todo']} | {total['in_progress']} | {total['blocked']} | {total['done']} | "
        f"{len(all_stories)} |"
    )
    lines.append("")
    lines.append("## By phase")
    lines.append("")
    for phase in sorted(PHASE_NAMES):
        stories = sorted((s for _, s in all_stories if s.phase == phase), key=lambda s: s.id)
        if not stories:
            continue
        done = sum(1 for s in stories if s.status == "done")
        lines.append(f"### Phase {phase}: {PHASE_NAMES[phase]} ({done}/{len(stories)} done)")
        lines.append("")
        for s in stories:
            owner = f" ({s.owner})" if s.owner else ""
            lines.append(f"- `{s.status}` **{s.id}** {_cell(s.title)}{owner}")
        lines.append("")
    lines.append("## By epic")
    lines.append("")
    for e in epics:
        lines.append(f"### {e.epic}: {_cell(e.name)}")
        lines.append("")
        if e.owner_hint:
            lines.append(f"Owner hint: {_cell(e.owner_hint)}")
            lines.append("")
        lines.append("| Id | Title | Status | Phase | Owner | Branch | Depends on | Acceptance |")
        lines.append("|---|---|---|---:|---|---|---|---|")
        for s in sorted(e.stories, key=lambda s: s.id):
            lines.append(
                f"| {s.id} | {_cell(s.title)} | {s.status} | {s.phase} | {_cell(s.owner)} | "
                f"{_cell(s.branch)} | {', '.join(s.depends_on)} | {_cell(s.acceptance)} |"
            )
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str]) -> int:
    content = render(load_epics())
    if "--check" in argv:
        current = OUT.read_text() if OUT.exists() else ""
        if current != content:
            print(f"{OUT.relative_to(ROOT)} is stale: run `make tracker`", file=sys.stderr)
            return 1
        print("tracker up to date")
        return 0
    OUT.write_text(content)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
