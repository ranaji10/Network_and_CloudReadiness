"""Regenerate src/readiness/data/ccm_v4.1.json from the CSA spreadsheets in reference/.

Usage: uv run python scripts/build_control_catalog.py"""

from __future__ import annotations

import json
from pathlib import Path

import openpyxl

ROOT = Path(__file__).resolve().parents[1]
REF = ROOT / "reference" / "csa-ccm-caiq-v4.1"
OUT = ROOT / "src" / "readiness" / "data" / "ccm_v4.1.json"


def main() -> None:
    ccm = openpyxl.load_workbook(next(REF.glob("CCMv4.1.0-*.xlsx")), read_only=True)
    caiq = openpyxl.load_workbook(next(REF.glob("CAIQv4.1.0-*.xlsx")), read_only=True)
    controls: dict[str, dict] = {}
    for row in ccm["CCM"].iter_rows(min_row=4, values_only=True):
        dom, title, cid, spec = (tuple(row) + (None,) * 4)[:4]
        if cid and dom and title and spec:
            controls[cid] = {
                "id": cid,
                "domain": dom.strip(),
                "domain_code": cid.split("-")[0],
                "title": title.strip(),
                "specification": spec.strip(),
                "questions": [],
            }
    for row in caiq["CAIQv4.1.0"].iter_rows(min_row=3, values_only=True):
        qid, q = (tuple(row) + (None,) * 2)[:2]
        if qid and q and "." in qid:
            cid = qid.rsplit(".", 1)[0]
            if cid in controls:
                controls[cid]["questions"].append({"id": qid, "text": q.strip()})
    domains = sorted({(c["domain_code"], c["domain"]) for c in controls.values()})
    out = {
        "source": (
            "Cloud Security Alliance, Cloud Controls Matrix v4.1.0 and CAIQ v4.1.0 "
            "(see reference/csa-ccm-caiq-v4.1/). Generated by scripts/build_control_catalog.py; do not edit by hand."
        ),
        "version": "4.1.0",
        "domains": [{"code": a, "name": b} for a, b in domains],
        "controls": list(controls.values()),
    }
    OUT.write_text(json.dumps(out, indent=1))
    print(f"{len(controls)} controls, {sum(len(c['questions']) for c in controls.values())} questions -> {OUT}")


if __name__ == "__main__":
    main()
