"""Mirror docs/planning/tracker/*.yaml into GitHub Issues (optional, one-way: YAML -> Issues).

Every story becomes one issue whose title starts with ``<STORY-ID>: `` (the idempotency key). The body
carries status, phase, owner, branch, dependencies, acceptance and notes; labels are ``epic:<EPIC>``,
``phase:<n>`` and ``status:<status>``. A ``done`` story closes its issue, any other status (re)opens it.
Issues whose title, body, labels and state already match are left untouched. Edits made on GitHub are
overwritten on the next run: the tracker YAML stays the source of truth (see docs/planning/README.md).

Usage:
    uv run python scripts/tracker_to_issues.py --dry-run                 # print what would change
    GITHUB_TOKEN=... uv run python scripts/tracker_to_issues.py --repo owner/repo
    uv run python scripts/tracker_to_issues.py --only DOC-06 --only DOC-05

Environment: GITHUB_TOKEN (required unless --dry-run), GITHUB_REPOSITORY (owner/repo, or pass --repo),
GITHUB_API_URL (defaults to https://api.github.com). The token is never printed.
"""

import argparse
import importlib.util
import os
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import httpx
import yaml

ROOT = Path(__file__).resolve().parents[1]
TRACKER_DIR = ROOT / "docs" / "planning" / "tracker"
DEFAULT_API_URL = "https://api.github.com"
STORY_PREFIX = re.compile(r"^([A-Z]+-\d+): ")
PER_PAGE = 100
STATUS_COLOURS = {"todo": "ededed", "in_progress": "fbca04", "blocked": "d93f0b", "done": "0e8a16"}
EPIC_COLOUR = "1d76db"
PHASE_COLOUR = "5319e7"
SOURCE_OF_TRUTH = (
    "_Source of truth: `docs/planning/tracker/{epic}.yaml` in the repository. This issue is generated by "
    "`scripts/tracker_to_issues.py`; edit the YAML, not the issue, or your change is overwritten on the next sync._"
)


def _load_render_tracker() -> Any:
    """Reuse the Story/Epic schema from render_tracker.py so the two scripts never disagree."""
    path = Path(__file__).resolve().with_name("render_tracker.py")
    spec = importlib.util.spec_from_file_location("render_tracker", path)
    if spec is None or spec.loader is None:  # pragma: no cover - the file sits next to this one
        raise RuntimeError(f"cannot load {path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules.setdefault(spec.name, module)  # pydantic resolves the forward refs through sys.modules
    spec.loader.exec_module(module)
    return module


_tracker = _load_render_tracker()
Epic = _tracker.Epic
Story = _tracker.Story


def load_epics(tracker_dir: Path = TRACKER_DIR) -> list[Any]:
    """Load and validate every epic file; the full cross-file validation lives in render_tracker.py."""
    return [Epic.model_validate(yaml.safe_load(p.read_text())) for p in sorted(tracker_dir.glob("*.yaml"))]


# --------------------------------------------------------------------------- desired state


@dataclass(frozen=True)
class Desired:
    story_id: str
    title: str
    body: str
    labels: tuple[str, ...]
    state: str  # "open" | "closed"

    @property
    def closed(self) -> bool:
        return self.state == "closed"


def desired_for(epic: Any, story: Any) -> Desired:
    owner = story.owner or "_unassigned_"
    branch = f"`{story.branch}`" if story.branch else "_none_"
    depends = ", ".join(story.depends_on) if story.depends_on else "_none_"
    lines = [
        f"**Status:** `{story.status}`",
        f"**Phase:** {story.phase}",
        f"**Owner:** {owner}",
        f"**Branch:** {branch}",
        f"**Depends on:** {depends}",
        "",
        "### Acceptance",
        "",
        story.acceptance or "_not specified_",
        "",
        "### Notes",
        "",
        story.notes or "_none_",
        "",
        "---",
        "",
        SOURCE_OF_TRUTH.format(epic=epic.epic),
    ]
    labels = (f"epic:{epic.epic}", f"phase:{story.phase}", f"status:{story.status}")
    return Desired(
        story_id=story.id,
        title=f"{story.id}: {story.title}",
        body="\n".join(lines),
        labels=labels,
        state="closed" if story.status == "done" else "open",
    )


def label_colour(name: str) -> str:
    kind, _, value = name.partition(":")
    if kind == "status":
        return STATUS_COLOURS.get(value, "ededed")
    return PHASE_COLOUR if kind == "phase" else EPIC_COLOUR


# --------------------------------------------------------------------------- github client


class GitHubClient:
    """Thin wrapper over the REST API. Pass ``client`` to use a custom transport (tests use MockTransport)."""

    def __init__(
        self,
        repo: str,
        token: str | None,
        client: httpx.Client | None = None,
        api_url: str = DEFAULT_API_URL,
    ) -> None:
        self.repo = repo
        self.api_url = api_url.rstrip("/")
        self.client = client or httpx.Client(timeout=30)
        self.client.headers.update({"Accept": "application/vnd.github+json", "X-GitHub-Api-Version": "2022-11-28"})
        if token:
            self.client.headers["Authorization"] = f"Bearer {token}"

    def _url(self, path: str) -> str:
        return f"{self.api_url}/repos/{self.repo}/{path}"

    def _paginate(self, path: str, params: dict[str, Any]) -> list[dict[str, Any]]:
        out: list[dict[str, Any]] = []
        page = 1
        while True:
            r = self.client.get(self._url(path), params={**params, "per_page": PER_PAGE, "page": page})
            r.raise_for_status()
            batch = r.json()
            out.extend(batch)
            if len(batch) < PER_PAGE:
                return out
            page += 1

    def list_issues(self) -> list[dict[str, Any]]:
        """Every issue (open and closed); pull requests share the endpoint and are dropped."""
        return [i for i in self._paginate("issues", {"state": "all"}) if "pull_request" not in i]

    def list_labels(self) -> set[str]:
        return {lab["name"] for lab in self._paginate("labels", {})}

    def ensure_label(self, name: str) -> None:
        r = self.client.post(self._url("labels"), json={"name": name, "color": label_colour(name)})
        if r.status_code == 422:  # already exists (created concurrently or listed stale)
            return
        r.raise_for_status()

    def create_issue(self, desired: Desired) -> dict[str, Any]:
        r = self.client.post(
            self._url("issues"),
            json={"title": desired.title, "body": desired.body, "labels": list(desired.labels)},
        )
        r.raise_for_status()
        return r.json()

    def update_issue(self, number: int, fields: dict[str, Any]) -> dict[str, Any]:
        r = self.client.patch(self._url(f"issues/{number}"), json=fields)
        r.raise_for_status()
        return r.json()


# --------------------------------------------------------------------------- sync


@dataclass
class Change:
    story_id: str
    action: str  # "create" | "update" | "unchanged"
    number: int | None = None
    fields: list[str] = field(default_factory=list)

    def __str__(self) -> str:
        ref = f" #{self.number}" if self.number else ""
        detail = f" [{', '.join(self.fields)}]" if self.fields else ""
        return f"{self.story_id}: {self.action}{ref}{detail}"


@dataclass
class SyncResult:
    changes: list[Change] = field(default_factory=list)
    new_labels: list[str] = field(default_factory=list)
    duplicates: dict[str, list[int]] = field(default_factory=dict)

    @property
    def writes(self) -> list[Change]:
        return [c for c in self.changes if c.action != "unchanged"]


def _norm(text: str | None) -> str:
    return (text or "").replace("\r\n", "\n").strip()


def diff_fields(existing: dict[str, Any], desired: Desired) -> dict[str, Any]:
    """The PATCH payload that brings ``existing`` to ``desired``; empty when nothing differs."""
    fields: dict[str, Any] = {}
    if existing.get("title") != desired.title:
        fields["title"] = desired.title
    if _norm(existing.get("body")) != _norm(desired.body):
        fields["body"] = desired.body
    have = {lab["name"] if isinstance(lab, dict) else str(lab) for lab in existing.get("labels", [])}
    if have != set(desired.labels):
        fields["labels"] = list(desired.labels)
    if existing.get("state") != desired.state:
        fields["state"] = desired.state
        fields["state_reason"] = "completed" if desired.closed else "reopened"
    return fields


def index_by_story(issues: list[dict[str, Any]]) -> tuple[dict[str, dict[str, Any]], dict[str, list[int]]]:
    """Map story id -> issue (lowest number wins) and report any duplicates."""
    by_story: dict[str, dict[str, Any]] = {}
    seen: dict[str, list[int]] = {}
    for issue in sorted(issues, key=lambda i: i["number"]):
        m = STORY_PREFIX.match(issue.get("title") or "")
        if not m:
            continue
        seen.setdefault(m.group(1), []).append(issue["number"])
        by_story.setdefault(m.group(1), issue)
    return by_story, {k: v for k, v in seen.items() if len(v) > 1}


def sync(
    epics: list[Any],
    gh: GitHubClient,
    *,
    dry_run: bool = False,
    only: set[str] | None = None,
) -> SyncResult:
    result = SyncResult()
    wanted = [desired_for(e, s) for e in epics for s in e.stories if not only or s.id in only]
    if not wanted:
        return result
    by_story, result.duplicates = index_by_story(gh.list_issues())
    have_labels = gh.list_labels()
    result.new_labels = sorted({lab for d in wanted for lab in d.labels} - have_labels)
    if not dry_run:
        for name in result.new_labels:
            gh.ensure_label(name)
    for desired in wanted:
        existing = by_story.get(desired.story_id)
        if existing is None:
            change = Change(desired.story_id, "create", fields=["state"] if desired.closed else [])
            if not dry_run:
                created = gh.create_issue(desired)
                change.number = created["number"]
                if desired.closed:
                    gh.update_issue(created["number"], {"state": "closed", "state_reason": "completed"})
        else:
            fields = diff_fields(existing, desired)
            names = [k for k in fields if k != "state_reason"]
            change = Change(desired.story_id, "update" if fields else "unchanged", existing["number"], names)
            if fields and not dry_run:
                gh.update_issue(existing["number"], fields)
        result.changes.append(change)
    return result


# --------------------------------------------------------------------------- cli


def parse_args(argv: list[str]) -> argparse.Namespace:
    ap = argparse.ArgumentParser(
        description=__doc__.split("\n\n")[0], formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument(
        "--repo", default=os.environ.get("GITHUB_REPOSITORY", ""), help="owner/repo (or $GITHUB_REPOSITORY)"
    )
    ap.add_argument("--dry-run", action="store_true", help="read the API, print the plan, write nothing")
    ap.add_argument(
        "--only", action="append", default=[], metavar="STORY-ID", help="limit to these stories (repeatable)"
    )
    ap.add_argument("--tracker-dir", type=Path, default=TRACKER_DIR, help=argparse.SUPPRESS)
    ap.add_argument("--api-url", default=os.environ.get("GITHUB_API_URL", DEFAULT_API_URL), help=argparse.SUPPRESS)
    return ap.parse_args(argv)


def main(argv: list[str] | None = None, client: httpx.Client | None = None) -> int:
    a = parse_args(sys.argv[1:] if argv is None else argv)
    token = os.environ.get("GITHUB_TOKEN") or None
    if not a.repo or "/" not in a.repo:
        print("error: set GITHUB_REPOSITORY=owner/repo or pass --repo owner/repo", file=sys.stderr)
        return 2
    if not token and not a.dry_run:
        print("error: GITHUB_TOKEN is required unless --dry-run", file=sys.stderr)
        return 2
    epics = load_epics(a.tracker_dir)
    only = set(a.only) or None
    known = {s.id for e in epics for s in e.stories}
    if only and only - known:
        print(f"error: unknown story id(s): {sorted(only - known)}", file=sys.stderr)
        return 2
    gh = GitHubClient(a.repo, token, client=client, api_url=a.api_url)
    mode = "dry run, nothing written" if a.dry_run else "applying"
    print(f"tracker -> issues for {a.repo} ({mode})")
    try:
        result = sync(epics, gh, dry_run=a.dry_run, only=only)
    except httpx.HTTPStatusError as exc:
        print(
            f"error: GitHub API {exc.response.status_code} on {exc.request.method} {exc.request.url}", file=sys.stderr
        )
        return 1
    except httpx.HTTPError as exc:
        print(f"error: {type(exc).__name__} talking to the GitHub API", file=sys.stderr)
        return 1
    for name in result.new_labels:
        print(f"label: {'would create' if a.dry_run else 'created'} {name}")
    for change in result.changes:
        print(f"{'would ' if a.dry_run and change.action != 'unchanged' else ''}{change}")
    for story_id, numbers in sorted(result.duplicates.items()):
        print(f"warning: {story_id} matches several issues {numbers}; the lowest number is used", file=sys.stderr)
    verb = "to change" if a.dry_run else "changed"
    print(f"{len(result.changes)} stories, {len(result.writes)} {verb}, {len(result.new_labels)} new labels")
    return 0


if __name__ == "__main__":
    sys.exit(main())
