"""Evaluation harness for the synthetic document packs under tests/evals/packs/.

Each pack is a folder with a `docs/` sub-folder (the documents the pipeline reads) and an `expected.yaml`
that pins the scores the current scoring configuration produces for it. `tests/evals/test_evals.py` runs
every pack offline, with the mock LLM, in two modes (rules only, and rules + LLM judge) and fails when a
score drifts beyond the pack's tolerance or a designed check status changes.

Run as a script to see current values against the pinned ones, or to refresh the pinned numbers after an
intended change to `config/scoring/*.yaml` or `config/profiles/*.yaml`:

    uv run python tests/evals/generate_expected.py            # report drift, exit 1 beyond tolerance
    uv run python tests/evals/generate_expected.py --write    # refresh rules/judge blocks (review the diff!)
    uv run python tests/evals/generate_expected.py --verbose  # per-check statuses and document classes

Only the generated blocks (`rules`, and `judge` when it differs) are rewritten; the hand-written design
fields (`description`, `profile`, `tolerance`, `tolerances`, `documents`, `document_classes`, `checks`) are
kept as they are. No network access is needed: `READINESS_LLM_PROVIDER=mock` and egress stays disabled."""

from __future__ import annotations

import argparse
import sys
import tempfile
from pathlib import Path
from typing import Any

import yaml

from readiness.config import DEFAULT_CONFIG_DIR, Settings
from readiness.models import AssessmentReport
from readiness.pipeline import run_assessment

PACKS_DIR = Path(__file__).resolve().parent / "packs"
MODES = ("rules", "judge")
DEFAULT_TOLERANCE = 1.0
HEADER = (
    "# Expected scores for this SYNTHETIC evaluation pack. The `rules` block (and `judge`, when it differs) is\n"
    "# generated by `make evals-refresh` (tests/evals/generate_expected.py --write); edit the other fields by hand.\n"
)
# Key order of expected.yaml: design fields first, generated blocks last.
FIELD_ORDER = (
    "pack",
    "description",
    "profile",
    "tolerance",
    "tolerances",
    "documents",
    "document_classes",
    "warnings_contain",
    "checks",
    "rules",
    "judge",
)


def list_packs(packs_dir: Path = PACKS_DIR) -> list[Path]:
    return sorted(p for p in packs_dir.iterdir() if p.is_dir() and (p / "docs").is_dir())


def make_settings(workspace: Path, mode: str) -> Settings:
    """Offline settings, independent of any developer .env or READINESS_* variable that could skew a score."""
    return Settings(
        _env_file=None,
        provider="local",
        llm_provider="mock",
        allow_llm_egress=False,
        use_llm_judge=(mode == "judge"),
        use_llm_classifier=False,
        redaction_mode="pseudonymize",
        include_evidence_snippets=False,
        workspace_dir=workspace,
        config_dir=DEFAULT_CONFIG_DIR,
        tenant_id="evals",
        auth_disabled=True,
    )


def run_pack(pack: Path, mode: str, profile: str, workspace: Path) -> AssessmentReport:
    report, _ = run_assessment(f"file://{pack / 'docs'}", make_settings(workspace, mode), profile, write_outputs=False)
    return report


def summarise(report: AssessmentReport) -> dict[str, Any]:
    """The numbers that get pinned: composite score/coverage and per-domain posture score/coverage."""
    return {
        "overall_score": report.overall_score,
        "overall_coverage": report.overall_coverage,
        "domains": {d.domain_id: {"score": d.score, "coverage": d.coverage} for d in report.domains},
    }


def check_statuses(report: AssessmentReport) -> dict[str, str]:
    return {c.check_id: str(c.status) for d in report.domains for p in d.pillars for c in p.checks}


def document_classes(report: AssessmentReport) -> dict[str, str]:
    return {doc.name: report.document_classes.get(doc.id, "") for doc in report.documents}


def load_expected(pack: Path) -> dict[str, Any]:
    path = pack / "expected.yaml"
    if not path.exists():
        return {"pack": pack.name, "profile": "default", "tolerance": DEFAULT_TOLERANCE}
    data = yaml.safe_load(path.read_text()) or {}
    data.setdefault("pack", pack.name)
    data.setdefault("profile", "default")
    data.setdefault("tolerance", DEFAULT_TOLERANCE)
    return data


def expected_numbers(expected: dict[str, Any], mode: str) -> dict[str, Any] | None:
    """`judge` falls back to `rules` when the two modes produce the same numbers."""
    if mode == "judge" and expected.get("judge"):
        return expected["judge"]
    return expected.get("rules")


def flatten(numbers: dict[str, Any]) -> dict[str, float]:
    flat = {"overall_score": numbers["overall_score"], "overall_coverage": numbers["overall_coverage"]}
    for dom, vals in numbers.get("domains", {}).items():
        flat[f"{dom}.score"] = vals["score"]
        flat[f"{dom}.coverage"] = vals["coverage"]
    return flat


def tolerance_for(expected: dict[str, Any], key: str) -> float:
    return float((expected.get("tolerances") or {}).get(key, expected.get("tolerance", DEFAULT_TOLERANCE)))


def drift(expected: dict[str, Any], mode: str, actual: dict[str, Any]) -> list[str]:
    """Human-readable list of every pinned value outside its tolerance (empty when all is well)."""
    pinned = expected_numbers(expected, mode)
    if pinned is None:
        return [f"{expected['pack']}[{mode}]: no pinned values (run with --write)"]
    want, got = flatten(pinned), flatten(actual)
    problems = []
    for key in sorted(set(want) | set(got)):
        if key not in want or key not in got:
            problems.append(f"{expected['pack']}[{mode}] {key}: expected {want.get(key)} got {got.get(key)}")
            continue
        tol = tolerance_for(expected, key)
        if abs(want[key] - got[key]) > tol:
            problems.append(f"{expected['pack']}[{mode}] {key}: expected {want[key]} +/- {tol}, got {got[key]}")
    return problems


def write_expected(pack: Path, expected: dict[str, Any], rules: dict[str, Any], judge: dict[str, Any]) -> bool:
    """Rewrite expected.yaml with fresh generated blocks; returns True when the file changed."""
    data = dict(expected)
    data["rules"] = rules
    if judge != rules:
        data["judge"] = judge
    else:
        data.pop("judge", None)
    ordered = {k: data[k] for k in FIELD_ORDER if k in data}
    ordered.update({k: v for k, v in data.items() if k not in ordered})
    text = HEADER + yaml.safe_dump(ordered, sort_keys=False, allow_unicode=True, width=110)
    path = pack / "expected.yaml"
    if path.exists() and path.read_text() == text:
        return False
    path.write_text(text)
    return True


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write", action="store_true", help="refresh the generated blocks of every expected.yaml")
    ap.add_argument("--verbose", action="store_true", help="print per-check statuses and document classes")
    ap.add_argument("--pack", action="append", help="only these pack ids (repeatable)")
    args = ap.parse_args(argv)

    packs = [p for p in list_packs() if not args.pack or p.name in args.pack]
    if not packs:
        print("no packs found", file=sys.stderr)
        return 2
    problems: list[str] = []
    changed: list[str] = []
    with tempfile.TemporaryDirectory() as tmp:
        for pack in packs:
            expected = load_expected(pack)
            reports = {mode: run_pack(pack, mode, expected["profile"], Path(tmp)) for mode in MODES}
            numbers = {mode: summarise(r) for mode, r in reports.items()}
            r = reports["rules"]
            print(
                f"{pack.name:<28} profile={expected['profile']:<14} score={r.overall_score:>5}  "
                f"coverage={r.overall_coverage:>5}  docs={len(r.documents)}  "
                + "  ".join(f"{d.domain_id.split('_')[0]}={d.score}/{d.coverage}" for d in r.domains)
            )
            if args.verbose:
                for name, cls in document_classes(r).items():
                    print(f"    doc  {name:<40} {cls}")
                statuses = check_statuses(r)
                for mode in MODES:
                    if check_statuses(reports[mode]) != statuses:
                        print("    note: judge mode statuses differ from rules mode")
                for cid, st in statuses.items():
                    print(f"    {cid:<10} {st}")
                for w in r.warnings:
                    print(f"    warning: {w}")
            if args.write:
                if write_expected(pack, expected, numbers["rules"], numbers["judge"]):
                    changed.append(pack.name)
            else:
                for mode in MODES:
                    problems.extend(drift(expected, mode, numbers[mode]))
    if args.write:
        print(f"refreshed {len(changed)} expected.yaml file(s): {', '.join(changed) or 'none'}")
        return 0
    if problems:
        print("\nScore drift beyond tolerance (re-run with --write if the change is intended):")
        print("\n".join(problems))
        return 1
    print("\nall packs within tolerance")
    return 0


if __name__ == "__main__":
    sys.exit(main())
